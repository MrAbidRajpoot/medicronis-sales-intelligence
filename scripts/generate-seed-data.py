    EXPLICIT: dict[str, str] = {}
    target_products = sorted({r["productName"] for r in all_rows})
    unmatched = []
    for tp in target_products:
        sku = match_sku(tp)
        if sku:
            EXPLICIT[tp] = sku
        else:
            unmatched.append(tp)

    print("\n=== Unmatched target products ===")
    for u in unmatched:
        # show best candidate
        best = max(products, key=lambda p: SequenceMatcher(None, norm_key(u), norm_key(p["name"])).ratio())
        score = SequenceMatcher(None, norm_key(u), norm_key(best["name"])).ratio()
