def parse_target_sheet(path: Path, sheet: str):
    import openpyxl

    # read_only + max_col avoids MemoryError on large Trade workbook
    wb = openpyxl.load_workbook(path, data_only=True, read_only=True)
    ws = wb[sheet]
    hdr_i = None
    hdr = None
    month_cols: list[tuple[int, int, int]] = []
    out = []

    for i, r in enumerate(ws.iter_rows(min_col=1, max_col=20, values_only=True)):
        if hdr_i is None:
            if r and len(r) > 9 and r[3] == "Name" and r[5] == "Territory":
                hdr_i = i
                hdr = r
                for ci, v in enumerate(hdr):
                    if isinstance(v, datetime):
                        month_cols.append((ci, v.year, v.month))
            continue

        if not r or not r[5] or not r[9]:
            continue
        product = str(r[9]).strip()
        if product.upper() in ("TOTAL UNITS", "TOTAL VALUE", "PRODUCT NAME"):
            continue
        manager = str(r[3]).strip() if r[3] else "Vacant"
        if not manager:
            manager = "Vacant"
        desig = str(r[4]).strip() if r[4] else None
        terr = str(r[5]).strip()
        area = str(r[6]).strip() if r[6] else None
        region = str(r[7]).strip() if r[7] else None
        zone = str(r[8]).strip() if r[8] else None
        if not terr or not area or not region or not zone or not product:
            continue
        months = []
        for ci, y, m in month_cols:
            q = r[ci] if ci < len(r) else None
            if q is None or q == "":
                continue
            try:
                qf = float(q)
            except Exception:
                continue
            if qf < 0:
                continue
            months.append({"year": y, "month": m, "quantity": qf})
        out.append(
            {
                "manager": manager,
                "designation": desig,
                "territory": terr,
                "area": area,
                "region": region,
                "zone": zone,
                "productName": product,
                "months": months,
            }
        )

    wb.close()
    if hdr_i is None:
        raise RuntimeError(f"Header not found in {path.name}/{sheet}")
    return out


