    def pick_manager(counter_by_desig_name: dict, rank_map: dict) -> str:
        # counter keys (manager, desig) -> count
        best = None
        best_key = (999, -1, "")
        for (mgr, desig), cnt in counter_by_desig_name.items():
            rank = rank_map.get(desig or "", 50)
            key = (rank, -cnt, mgr)
            if best is None or key < best_key:
                best = mgr
                best_key = key
        return best or "Vacant"

