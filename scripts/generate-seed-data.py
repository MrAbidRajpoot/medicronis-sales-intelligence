def ts_escape(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def write_ts_const(path: Path, export_name: str, value) -> None:
    body = json.dumps(value, indent=2, ensure_ascii=False)
    # Prefer TypeScript `as const` for type narrowing where useful
    path.write_text(
        f"/* Auto-generated by scripts/generate-seed-data.py — do not edit by hand */\n"
        f"export const {export_name} = {body} as const;\n",
        encoding="utf-8",
    )
    print(f"wrote {path.relative_to(ROOT)} ({len(value) if hasattr(value, '__len__') else 'obj'})")


def load_products():
    import openpyxl

    wb = openpyxl.load_workbook(PRODUCT_XLSX, data_only=True)
    ws = wb["Products"]
    products = []
    for r in ws.iter_rows(min_row=2, values_only=True):
        if not r or not r[0]:
            continue
        sku = str(r[0]).strip()
        name = str(r[1]).strip() if r[1] else ""
        category = str(r[2]).strip() if r[2] else None
        group_raw = str(r[4]).strip() if r[4] else "Trade"
        group = GROUP_MAP.get(group_raw.lower(), group_raw)
        composition = str(r[5]).strip() if r[5] else None
        manufacturer = str(r[6]).strip() if r[6] else None
        shipper = int(r[7]) if r[7] is not None and str(r[7]).strip() != "" else None
        def num(v):
            if v is None or v == "":
                return None
            try:
                return float(v)
            except Exception:
                return None

        aliases_raw = str(r[16]).strip() if len(r) > 16 and r[16] else ""
        aliases = [a.strip() for a in aliases_raw.split(",") if a.strip()] if aliases_raw else []
        # Sheet "aliases" often repeat composition/manufacturer — still seed as provided
        products.append(
            {
                "sku": sku,
                "name": name,
                "category": category,
                "group": group,
                "composition": composition,
                "manufacturer": manufacturer,
                "shipperSize": shipper,
                "mrp": num(r[8]),
                "tp": num(r[9]),
                "oldSp": num(r[10]),
                "newSp": num(r[11]),
                "netPrice": num(r[12]),
                "tax": num(r[13]),
                "netPriceWith1Pct": num(r[14]),
                "bonus": str(r[15]).strip() if r[15] else None,
                "aliases": aliases,
            }
        )
    wb.close()
    return products


def norm_key(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "", s.lower())


def build_product_matcher(products):
    by_exact = {p["name"]: p["sku"] for p in products}
    by_norm = {norm_key(p["name"]): p["sku"] for p in products}
    # also index aliases
    for p in products:
        for a in p["aliases"]:
            by_exact.setdefault(a, p["sku"])
            by_norm.setdefault(norm_key(a), p["sku"])
    return by_exact, by_norm, products


